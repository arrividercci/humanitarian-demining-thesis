package com.riskgrid.mining;

import java.util.concurrent.ConcurrentHashMap;
import java.util.Set;

/**
 * Координація кількох паралельних дронів (розділ 3.6): гарантує, що жодні
 * два дрони не оберуть одну й ту саму клітинку метою одночасно.
 *
 * Механізм навмисно простий - атомарне "застовплення" клітинки через
 * ConcurrentHashMap.putIfAbsent. Це свідомий вибір: складніші механізми
 * (лізинг з таймаутом, розподілений консенсус) не потрібні в контрольованому
 * середовищі симуляції і лише ускладнили б формальне обґрунтування, не
 * підсилюючи наукову новизну роботи (яка полягає в доведеному правилі
 * злиття оновлень RiskGrid, а не в координації агентів).
 *
 * Клас потоко-безпечний і не має зовнішніх залежностей від RiskGrid -
 * оперує лише індексами клітинок.
 */
public class DroneCoordinator {

    // Значення не використовується - лише сам факт присутності ключа
    // означає "клітинка застовплена". Boolean.TRUE - канонічне значення.
    private final ConcurrentHashMap<Long, Boolean> claimedCells = new ConcurrentHashMap<>();

    /**
     * Пакує координати клітинки (i, j) в один long-ключ.
     * Формат: старші 32 біти - i, молодші 32 біти - j.
     * Підходить для сіток розміром до 2^31 клітинок по кожній осі -
     * з великим запасом для будь-якого реалістичного розміру карти.
     */
    static long cellKey(int i, int j) {
        return (((long) i) << 32) | (j & 0xffffffffL);
    }

    /**
     * Намагається атомарно застовпити клітинку (i, j).
     *
     * @return true, якщо клітинку успішно застовплено (була вільна);
     *         false, якщо клітинка вже застовплена іншим дроном
     */
    public boolean tryClaim(int i, int j) {
        return claimedCells.putIfAbsent(cellKey(i, j), Boolean.TRUE) == null;
    }

    /**
     * Звільняє клітинку після того, як дрон долетів і застосував
     * спостереження до RiskGrid. Обов'язково викликати навіть у разі
     * помилки (finally-блок на боці виклику), інакше клітинка лишиться
     * "заблокованою" назавжди.
     */
    public void release(int i, int j) {
        claimedCells.remove(cellKey(i, j));
    }

    /**
     * Поточний набір застовплених клітинок - передається в
     * RoutePlanner.selectNextTarget(..., excludedCells) так, щоб дрон
     * не розглядав клітинки, які вже обрані іншими дронами.
     */
    public Set<Long> getClaimedCells() {
        return claimedCells.keySet();
    }

    /** Кількість наразі застовплених клітинок - зручно для діагностики/логів. */
    public int claimedCount() {
        return claimedCells.size();
    }
}
